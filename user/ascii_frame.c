/*******************************************************************************
* ascii_frame.c — ASCII 帧缓冲实现
*
* 用途: 将 USB 键盘输入的 ASCII 字符暂存于 reg_ascii[128], 该数组直接映射到
*   Modbus 保持寄存器 40001~40128 的低字节, 供 modbus_rtu.c 应答 0x03 读取。
*
* 核心状态机:
*   frame_idx  当前"帧尾"位置, 即下一个字符将写入的下标(0~127);
*              范围 [0, frame_idx) 为有效字符, [frame_idx, 128) 恒为 0。
*   idle_cnt   自上次字符写入/删除以来的主循环心跳数(主循环 2ms 一次),
*              用于实现"空闲超时自动提交"——模拟终端敲完一行字后自动发送。
*   pending_len 待读帧长度: 定帧(commit)时记录, 主站读 0x0088 获知;
*              新输入开始时作废(归 0)。
*   frame_no   帧号: 每次定帧 +1, 主站读 0x0089 比对变化判断"有新帧"。
*
* 帧生命周期(工业网关惯例: 帧号 + 长度 + 数据区, 覆盖式写入不清空):
*   输入中   -> frame_idx 递增, pending_len=0, 帧号不变(主站不读半帧)
*   定帧     -> Enter/空闲超时: pending_len=帧长, 帧号+1
*   上传     -> 主站: 读 0x0089 帧号(变化) + 0x0088 长度 → 按长度读数据区
*   下次输入 -> 覆盖式写入, 无残留可见(按长度读只取有效段)
*
* 与 modbus_rtu.c 的关系: 本模块只维护缓冲内容, 不做任何串口收发;
*   Modbus 主站轮询读寄存器时, 由 modbus_rtu.c 调用 ascii_frame_get() 取值。
*******************************************************************************/
#include "CH57x_common.h"
#include "ascii_frame.h"

/* reg_ascii[index] == Modbus 寄存器 40001+index 的低字节(高字节恒为 0) */
static UINT8  reg_ascii[ ASCII_FRAME_SIZE ];
static UINT8  frame_idx = 0;    /* 当前帧写入位置(=有效字符个数, 0~128) */
static UINT16 idle_cnt  = 0;    /* 空闲心跳计数(主循环约 2ms 递增一次) */
static UINT16 pending_len = 0;  /* 待读帧长度: 定帧(commit)时记录, 新输入开始=0 */
static UINT16 frame_no = 0;     /* 帧号: 每次定帧+1(主站比对变化判断新帧, 0x0089 读) */
static UINT16 g_idle_ms = ASCII_IDLE_MS_DEF;  /* 空闲超时(ms), 0=禁用; Modbus 0x0086 联动 */

/*******************************************************************************
* 设置空闲超时(ms)。0 = 禁用自动提交(仅 Enter 定帧)。
* 调用点: main 上电灌入 modbus_cfg 加载值; modbus_rtu 0x06 写 0x0086 后调用。
*******************************************************************************/
void ascii_frame_set_idle_ms( UINT16 ms )
{
    g_idle_ms = ms;
}

/*******************************************************************************
* 初始化: 全组清零 + 光标复位 + 待读长度清零, 清空空闲计时。
* 上电(main 中 ascii_frame_init())调用一次; 也可用于软复位寄存器组。
*******************************************************************************/
void ascii_frame_init( void )
{
    UINT8 i;
    for( i = 0; i < ASCII_FRAME_SIZE; i ++ ) reg_ascii[ i ] = 0;
    frame_idx = 0;
    idle_cnt  = 0;
    pending_len = 0;
    frame_no = 0;
}

/*******************************************************************************
* 追加一个字符 c 到当前帧尾。
* - 满帧(frame_idx >= 128)时静默忽略(不溢出、不覆写已写入的前段)。
* - 若上一帧已定帧但主站尚未读走(pending_len > 0), 新输入将其作废
*   (数据区即将被覆盖, 待读长度归 0; 帧号保持, 等新帧定帧才 +1 ——
*   主站以 0x0088=0 识别"旧帧已失效")。
* - 写入后重置空闲计数, 使"最近一次敲键"重新开始计时, 防止上一段被打断。
* 调用点: main.c process_key_events() 对可打印单字符键调用。
*******************************************************************************/
void ascii_frame_putch( char c )
{
    if( pending_len > 0 ) pending_len = 0;      /* 新输入作废旧待读帧标记 */
    if( frame_idx >= ASCII_FRAME_SIZE ) return;      /* 满帧忽略 */
    reg_ascii[ frame_idx ++ ] = ( UINT8 )c;
    idle_cnt = 0;                                    /* 重新开始空闲计时 */
}

/*******************************************************************************
* Backspace: 回退一位。把当前最后写入的字符位清零并把帧尾前移, 等效"删除"。
* - 空帧(frame_idx == 0)时不动作。
* - 清零的是"上一个已写入位"(reg_ascii[frame_idx-1]), 不是"下一个待写位"。
*******************************************************************************/
void ascii_frame_backspace( void )
{
    if( frame_idx > 0 )
    {
        frame_idx --;                    /* 帧尾前移 */
        reg_ascii[ frame_idx ] = 0;      /* 该位置清零(Modbus 读到 0) */
        idle_cnt = 0;                    /* 重新开始空闲计时 */
    }
}

/*******************************************************************************
* 立即提交(Enter 触发/空闲超时): 定帧并复位。
* 把当前帧 [0, frame_idx) 保留, 余段 [frame_idx, 128) 清 0, 帧尾回 0,
* 记录待读长度 pending_len = frame_idx, 并使帧号 +1 —— 主站读 0x0088 得
* 长度、0x0089 得帧号: 帧号变化 = 有新帧, 按长度读数据区即可(覆盖式写入,
* 不清空, 无 125 分段丢尾部问题)。
*******************************************************************************/
void ascii_frame_commit( void )
{
    UINT8 i;
    pending_len = frame_idx;                       /* 记录待读帧长度 */
    frame_no ++;                                   /* 帧号递增(新帧通知) */
    for( i = frame_idx; i < ASCII_FRAME_SIZE; i ++ ) reg_ascii[ i ] = 0;
    frame_idx = 0;                                 /* 光标回到起点 */
    idle_cnt  = 0;                                 /* 清空闲计时 */
}

/*******************************************************************************
* 待读帧长度: 定帧后 = 该帧字符数(>0, 主站据此读取); 新输入开始 = 0。
*******************************************************************************/
UINT16 ascii_frame_get_pending_len( void )
{
    return pending_len;
}

/*******************************************************************************
* 帧号: 每次定帧 +1。主站比对前后两次读取值, 变化即"有新帧待读"。
* 16 位回绕安全: 主站用"不等"比较即可(65536 帧后回绕仍会触发变化)。
*******************************************************************************/
UINT16 ascii_frame_get_frame_no( void )
{
    return frame_no;
}

/*******************************************************************************
* 主循环心跳驱动: 空闲超时自动提交。
* 每 2ms 被调一次。若 g_idle_ms 毫秒(约 g_idle_ms/2 次心跳)内无任何写入/删除/
*   提交动作, 且当前帧非空(frame_idx > 0), 则自动 commit(), 防止只有缓冲没
*   定帧导致 Modbus 一直读到不完整输入。
* - 空帧(frame_idx == 0)时只重置计时返回: 避免无输入时每超时无意义地
*   清空一次寄存器组(main 心跳打印等场景)。
* - g_idle_ms == 0 时禁用自动提交(仅 Enter 定帧)。
*******************************************************************************/
void ascii_frame_poll( void )
{
    UINT16 limit;

    if( g_idle_ms == 0 ) { idle_cnt = 0; return; }      /* 禁用自动提交 */
    if( frame_idx == 0 ) { idle_cnt = 0; return; }      /* 空帧不提交 */
    limit = ( UINT16 )( g_idle_ms >> 1 );               /* ms → 2ms 心跳数 */
    if( limit == 0 ) limit = 1;
    if( ++idle_cnt >= limit )
        ascii_frame_commit();
}

/*******************************************************************************
* 读取寄存器低字节(供 Modbus 应答)。index 越界时返回 0(防御)。
*******************************************************************************/
UINT8 ascii_frame_get( UINT8 index )
{
    if( index >= ASCII_FRAME_SIZE ) return 0;
    return reg_ascii[ index ];
}
