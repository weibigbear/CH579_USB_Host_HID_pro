/*******************************************************************************
* ascii_frame.c — ASCII 帧缓冲实现
*
* 用途: 将 USB 键盘输入的 ASCII 字符暂存于 reg_ascii[128], 该数组直接映射到
*   Modbus 保持寄存器 40001~40128 的低字节, 供 modbus_rtu.c 应答 0x03 读取。
*
* 核心状态机:
*   frame_idx  当前"帧尾"位置, 即下一个字符将写入的下标(0~127);
*              范围 [0, frame_idx) 为有效字符, [frame_idx, 128) 恒为 0。
*   idle_cnt   自上次字符写入/删除以来的主循环心跳数(主循环 2ms 一次),
*              用于实现"空闲超时自动提交"——模拟终端敲完一行字后自动发送。
*
* 提交语义: 提交不是"发送", 而是"定帧"——把当前输入的整段文本固定下来,
*   并对 Modbus 侧表现为: 余段清零 + 光标复位, 供下一段输入重新填充。
*
* 与 modbus_rtu.c 的关系: 本模块只维护缓冲内容, 不做任何串口收发;
*   Modbus 主站轮询读寄存器时, 由 modbus_rtu.c 调用 ascii_frame_get() 取值。
*******************************************************************************/
#include "CH57x_common.h"
#include "ascii_frame.h"

/* reg_ascii[index] == Modbus 寄存器 40001+index 的低字节(高字节恒为 0) */
static UINT8  reg_ascii[ ASCII_FRAME_SIZE ];
static UINT8  frame_idx = 0;    /* 当前帧写入位置(=有效字符个数, 0~128) */
static UINT16 idle_cnt  = 0;    /* 空闲心跳计数(主循环约 2ms 递增一次) */

/*******************************************************************************
* 初始化: 全组清零 + 光标复位, 清空空闲计时。
* 上电(main 中 ascii_frame_init())调用一次; 也可用于软复位寄存器组。
*******************************************************************************/
void ascii_frame_init( void )
{
    UINT8 i;
    for( i = 0; i < ASCII_FRAME_SIZE; i ++ ) reg_ascii[ i ] = 0;
    frame_idx = 0;
    idle_cnt  = 0;
}

/*******************************************************************************
* 追加一个字符 c 到当前帧尾。
* - 满帧(frame_idx >= 128)时静默忽略(不溢出、不覆写已写入的前段)。
* - 写入后重置空闲计数, 使"最近一次敲键"重新开始计时, 防止上一段被打断。
* 调用点: main.c process_key_events() 对可打印单字符键调用。
*******************************************************************************/
void ascii_frame_putch( char c )
{
    if( frame_idx >= ASCII_FRAME_SIZE ) return;      /* 满帧忽略 */
    reg_ascii[ frame_idx ++ ] = ( UINT8 )c;
    idle_cnt = 0;                                    /* 重新开始空闲计时 */
}

/*******************************************************************************
* Backspace: 回退一位。把当前最后写入的字符位清零并把帧尾前移, 等效"删除"。
* - 空帧(frame_idx == 0)时不动作。
* - 清零的是"上一个已写入位"(reg_ascii[frame_idx-1]), 不是"下一个待写位"。
*******************************************************************************/
void ascii_frame_backspace( void )
{
    if( frame_idx > 0 )
    {
        frame_idx --;                    /* 帧尾前移 */
        reg_ascii[ frame_idx ] = 0;      /* 该位置清零(Modbus 读到 0) */
        idle_cnt = 0;                    /* 重新开始空闲计时 */
    }
}

/*******************************************************************************
* 立即提交(Enter 触发): 定帧并复位。
* 把当前帧 [0, frame_idx) 保留, 余段 [frame_idx, 128) 清 0, 帧尾回 0。
* 这样 Modbus 只见一段完整输入; 下一次输入从头填充。
*******************************************************************************/
void ascii_frame_commit( void )
{
    UINT8 i;
    for( i = frame_idx; i < ASCII_FRAME_SIZE; i ++ ) reg_ascii[ i ] = 0;
    frame_idx = 0;                       /* 光标回到起点 */
    idle_cnt  = 0;                       /* 清空闲计时, 避免 commit 后立即被 poll 再次触发 */
}

/*******************************************************************************
* 主循环心跳驱动: 空闲超时自动提交。
* 每 2ms 被调一次。若 500ms(ASCII_IDLE_MS)内无任何写入/删除/提交动作,
*   且当前帧非空(frame_idx > 0), 则自动 commit(), 防止只有缓冲没定帧
*   导致 Modbus 一直读到不完整输入。
* - 空帧(frame_idx == 0)时只重置计时返回: 避免无输入时每 500ms 无意义地
*   清空一次寄存器组(main 心跳打印等场景)。
*******************************************************************************/
void ascii_frame_poll( void )
{
    if( frame_idx == 0 ) { idle_cnt = 0; return; }   /* 空帧不提交 */
    if( ++idle_cnt >= ( ASCII_IDLE_MS / 2 ) )        /* 500ms / 2ms 心跳 */
        ascii_frame_commit();
}

/*******************************************************************************
* 读取寄存器低字节(供 Modbus 应答)。index 越界时返回 0(防御)。
*******************************************************************************/
UINT8 ascii_frame_get( UINT8 index )
{
    if( index >= ASCII_FRAME_SIZE ) return 0;
    return reg_ascii[ index ];
}
